export type TextKey = keyof typeof tr;
export function t(key: TextKey, values: Record<string, string | number> = {}): string {
  return tr[key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}
export const number = (value: number, digits = 0) => new Intl.NumberFormat('tr-TR', {
  minimumFractionDigits: digits, maximumFractionDigits: digits,
}).format(Number.isFinite(value) ? value : 0);
